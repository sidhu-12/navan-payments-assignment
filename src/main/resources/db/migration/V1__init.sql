-- Live transactions ---------------------------------------------------------

CREATE TABLE transactions (
    id            VARCHAR(36) PRIMARY KEY,
    external_id   VARCHAR(255) NOT NULL,
    type          VARCHAR(32)  NOT NULL,
    currency      VARCHAR(3)   NOT NULL,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    total         DECIMAL(19, 2) NOT NULL,
    metadata_json CLOB NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_transactions_type CHECK (type IN ('flight', 'hotel', 'rail', 'navan_fee'))
);

CREATE UNIQUE INDEX uk_transactions_external_id ON transactions (external_id);

CREATE TABLE tax_lines (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  VARCHAR(36) NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    name            VARCHAR(255) NOT NULL,
    rate            DECIMAL(10, 6) NULL,
    amount          DECIMAL(19, 2) NOT NULL
);

CREATE INDEX idx_tax_lines_transaction_id ON tax_lines (transaction_id);

CREATE TABLE fee_lines (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  VARCHAR(36) NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    name            VARCHAR(255) NOT NULL,
    amount          DECIMAL(19, 2) NOT NULL
);

CREATE INDEX idx_fee_lines_transaction_id ON fee_lines (transaction_id);

CREATE TABLE flight_details (
    transaction_id  VARCHAR(36) PRIMARY KEY REFERENCES transactions (id) ON DELETE CASCADE,
    origin          VARCHAR(64) NOT NULL,
    destination     VARCHAR(64) NOT NULL,
    fare            DECIMAL(19, 2) NOT NULL
);

CREATE TABLE flight_coupons (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  VARCHAR(36) NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    position        INT NOT NULL,
    carrier         VARCHAR(16) NULL,
    flight_number   VARCHAR(32) NOT NULL,
    from_code       VARCHAR(64) NOT NULL,
    to_code         VARCHAR(64) NOT NULL,
    departure       TIMESTAMP WITH TIME ZONE NOT NULL,
    arrival         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_flight_coupons_transaction_id ON flight_coupons (transaction_id);

CREATE TABLE hotel_stays (
    transaction_id         VARCHAR(36) PRIMARY KEY REFERENCES transactions (id) ON DELETE CASCADE,
    name                   VARCHAR(255) NOT NULL,
    street                 VARCHAR(255) NOT NULL,
    city                   VARCHAR(128) NOT NULL,
    country                VARCHAR(64)  NOT NULL,
    check_in               DATE NOT NULL,
    check_out              DATE NOT NULL,
    nights                 INT NOT NULL,
    room_rate_per_night    DECIMAL(19, 2) NOT NULL
);

CREATE TABLE hotel_extras (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  VARCHAR(36) NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    name            VARCHAR(255) NOT NULL,
    amount          DECIMAL(19, 2) NOT NULL
);

CREATE INDEX idx_hotel_extras_transaction_id ON hotel_extras (transaction_id);

CREATE TABLE rail_legs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  VARCHAR(36) NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    position        INT NOT NULL,
    origin          VARCHAR(255) NOT NULL,
    destination     VARCHAR(255) NOT NULL,
    departure       TIMESTAMP WITH TIME ZONE NOT NULL,
    arrival         TIMESTAMP WITH TIME ZONE NOT NULL,
    train_number    VARCHAR(64) NULL,
    travel_class    VARCHAR(64) NULL
);

CREATE INDEX idx_rail_legs_transaction_id ON rail_legs (transaction_id);

CREATE TABLE navan_fee_details (
    transaction_id        VARCHAR(36) PRIMARY KEY REFERENCES transactions (id) ON DELETE CASCADE,
    fee_kind              VARCHAR(32) NOT NULL,
    description           VARCHAR(512) NULL,
    related_external_id   VARCHAR(255) NULL,
    CONSTRAINT chk_navan_fee_kind CHECK (fee_kind IN ('trip_fee', 'agent_call_fee'))
);

-- Invoice snapshots (copied at invoice time; not a live join) ---------------

CREATE TABLE invoices (
    id            VARCHAR(36) PRIMARY KEY,
    currency      VARCHAR(3) NOT NULL,
    grand_total   DECIMAL(19, 2) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE invoice_lines (
    id                VARCHAR(36) PRIMARY KEY,
    invoice_id        VARCHAR(36) NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    transaction_id    VARCHAR(36) NOT NULL REFERENCES transactions (id),
    type              VARCHAR(32) NOT NULL,
    total             DECIMAL(19, 2) NOT NULL,
    tax_lines_json    CLOB NOT NULL,
    fee_lines_json    CLOB NOT NULL,
    metadata_json     CLOB NOT NULL,
    position          INT NOT NULL
);

CREATE INDEX idx_invoice_lines_invoice_id ON invoice_lines (invoice_id);
CREATE INDEX idx_invoice_lines_transaction_id ON invoice_lines (transaction_id);

CREATE TABLE invoice_tax_rollups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  VARCHAR(36) NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    name        VARCHAR(255) NOT NULL,
    rate        DECIMAL(10, 6) NULL,
    amount      DECIMAL(19, 2) NOT NULL
);

CREATE INDEX idx_invoice_tax_rollups_invoice_id ON invoice_tax_rollups (invoice_id);

CREATE TABLE invoice_fee_rollups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  VARCHAR(36) NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    name        VARCHAR(255) NOT NULL,
    amount      DECIMAL(19, 2) NOT NULL
);

CREATE INDEX idx_invoice_fee_rollups_invoice_id ON invoice_fee_rollups (invoice_id);
